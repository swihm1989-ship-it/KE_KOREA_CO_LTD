"""Streamlit AppTest of the REAL MASTER screens with synthetic mail.

All cloud data, model and SMTP calls are mocked. In particular, no real
outbound email can be generated by this test.
"""
import unittest
from contextlib import ExitStack
from pathlib import Path
from unittest.mock import Mock, patch
from uuid import uuid4

from streamlit.testing.v1 import AppTest

PAGE=Path(__file__).resolve().parents[1]/"ui"/"streamlit_page.py"


class OutboxLiveUiTests(unittest.TestCase):
    def setUp(self):
        self.mail_id=str(uuid4())
        self.record={
            "id":self.mail_id,
            "owner_email":"owner@example.test",
            "source_subject":"입찰 건 관련",
            "source_body":"안녕하세요. 입찰 결과를 알려주세요.",
            "source_hash":"0"*64,
            "sender_header":"Buyer <buyer@example.test>",
            "recipient_email":"buyer@example.test",
            "candidate_bodies":[],
            "status":"draft",
            "language":"ko",
            "message_id":"<message@example.test>",
        }

    def _app(self,*,send=None,probe=None):
        send=send or Mock(return_value={"status":"sent","id":self.mail_id})
        probe=probe or Mock(return_value="진단 성공: 가상 테스트")
        stack=ExitStack()
        self.addCleanup(stack.close)
        patches=[
            ("Quotation_KEKOREA.orchestration.security.auth_gate.require_authentication",
             "owner@example.test"),
            ("Quotation_KEKOREA.orchestration.ui.market_news_page._cached_news",([],None)),
            ("Quotation_KEKOREA.orchestration.ui.email_outbox_page._db_env",{}),
            ("Quotation_KEKOREA.orchestration.ui.email_outbox_page.list_replies",[self.record]),
            ("Quotation_KEKOREA.orchestration.ui.pdf_archive_page.render_pdf_archive",None),
        ]
        for target,return_value in patches:
            stack.enter_context(patch(target,return_value=return_value))
        stack.enter_context(patch(
            "Quotation_KEKOREA.orchestration.ui.email_outbox_page.send_approved",send))
        stack.enter_context(patch(
            "Quotation_KEKOREA.orchestration.workflows.email_reply_runtime.probe_connection",probe))
        app=AppTest.from_file(str(PAGE),default_timeout=40).run()
        app.radio(key="master_page").set_value("발송 대기").run()
        self.assertFalse(app.exception,[x.message for x in app.exception])
        return app,send,probe

    def test_ai_outage_still_exposes_manual_draft_and_no_automatic_send(self):
        app,send,_probe=self._app()
        self.assertTrue(any(self.mail_id in str(b.key or "")
                            for b in app.text_area))
        self.assertFalse(app.button(key="master_reply_generate_"+self.mail_id).disabled is False)
        self.assertTrue(app.button(key="master_reply_send_"+self.mail_id).disabled)
        self.assertTrue(any("AI 후보" in x.value for x in app.info))
        send.assert_not_called()

    def test_manual_text_and_explicit_confirmation_are_required_for_sending(self):
        app,send,_probe=self._app()
        areas=[t for t in app.text_area
               if str(t.key or "").startswith("master_reply_body_"+self.mail_id)]
        self.assertEqual(len(areas),1)
        areas[0].set_value("안녕하세요. 답장을 확인한 후 연락드리겠습니다.").run()
        self.assertFalse(app.exception,[x.message for x in app.exception])
        self.assertTrue(app.button(key="master_reply_send_"+self.mail_id).disabled)
        checks=[c for c in app.checkbox if str(c.key or "").startswith(
            "master_reply_confirm_"+self.mail_id)]
        self.assertEqual(len(checks),1)
        checks[0].check().run()
        self.assertFalse(app.button(key="master_reply_send_"+self.mail_id).disabled)
        send.assert_not_called()
        app.button(key="master_reply_send_"+self.mail_id).click().run()
        self.assertFalse(app.exception,[x.message for x in app.exception])
        send.assert_called_once()
        args=send.call_args
        self.assertEqual(args.kwargs.get("confirmed"),True)
        self.assertEqual(args.kwargs.get("language"),"ko")
        self.assertIn("(주)케이이코리아",args.args[6])

    def test_provider_diagnostic_requires_one_explicit_click_with_dummy_content(self):
        app,_send,probe=self._app()
        self.assertTrue(app.button(key="master_reply_probe_"+self.mail_id).disabled)
        probe.assert_not_called()
        app.checkbox(key="master_reply_probe_consent_"+self.mail_id).check().run()
        self.assertFalse(app.button(key="master_reply_probe_"+self.mail_id).disabled)
        app.button(key="master_reply_probe_"+self.mail_id).click().run()
        self.assertFalse(app.exception,[x.message for x in app.exception])
        probe.assert_called_once()

if __name__=="__main__":
    unittest.main()
